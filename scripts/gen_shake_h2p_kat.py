#!/usr/bin/env python3
"""Generate known-answer tests for the SHAKE-256 hash-to-point.

The expected coefficients come from Python's own `hashlib.shake_256` with the Falcon
hash-to-point rule, independent of any Cairo code: absorb `salt || message`, read the
stream as big-endian 16-bit words, and accept `word % q` while `word < 5q` until 512
coefficients are collected. The salt is the two 20-byte little-endian salt felts and the
message is the 32 little-endian bytes of `message_hash`, matching
`hash_to_point_shake_512`. With `--falcon-py`, every vector is also checked against
falcon.py's `__hash_to_point__`.

Writes crates/falcon_512/tests/shake_h2p_kat.cairo.

Usage:
    python3 scripts/gen_shake_h2p_kat.py [--falcon-py /path/to/falcon.py-clone]
"""

import argparse
import hashlib
import re
import subprocess
import sys
from pathlib import Path

Q = 12289
N = 512
STARK_PRIME = 2**251 + 17 * 2**192 + 1
REPO = Path(__file__).resolve().parent.parent
FIXTURE = REPO / "crates/falcon_512/src/fixtures/shake.cairo"
OUT = REPO / "crates/falcon_512/tests/shake_h2p_kat.cairo"


def salt_bytes(salt_a: int, salt_b: int) -> bytes:
    return salt_a.to_bytes(20, "little") + salt_b.to_bytes(20, "little")


def hash_to_point(message_hash: int, salt_a: int, salt_b: int) -> list[int]:
    data = salt_bytes(salt_a, salt_b) + message_hash.to_bytes(32, "little")
    out: list[int] = []
    length = 2 * N
    while True:
        stream = hashlib.shake_256(data).digest(length)
        out = []
        for i in range(0, length, 2):
            word = (stream[i] << 8) | stream[i + 1]
            if word < 5 * Q:
                out.append(word % Q)
                if len(out) == N:
                    return out
        length *= 2


def fixture_vector() -> tuple[int, int, int]:
    src = FIXTURE.read_text()
    msg = int(re.search(r"pub fn msg\(\) -> felt252 \{\s*(\d+)", src).group(1))
    sig = [int(x, 16) for x in re.findall(r"0x[0-9a-f]+", src[src.index("pub fn signature"):])]
    return msg, sig[29], sig[30]


def emit(vectors: list[tuple[str, int, int, int, list[int]]]) -> str:
    lines = [
        "//! GENERATED by `scripts/gen_shake_h2p_kat.py` — do not edit by hand.",
        "//!",
        "//! Known-answer tests for `hash_to_point_shake_512`: every expected coefficient is",
        "//! computed by Python's `hashlib.shake_256` with the Falcon hash-to-point rule.",
        "",
        "use pqbench_falcon_512::hashing::hash_to_point::hash_to_point_shake_512;",
        "",
    ]
    for name, msg, salt_a, salt_b, coeffs in vectors:
        const = name.upper()
        lines.append(f"const {const}: [u16; {N}] = [{', '.join(str(c) for c in coeffs)}];")
        lines.append("")
        lines.append("#[test]")
        lines.append(f"fn test_hash_to_point_shake_kat_{name}() {{")
        lines.append(f"    let got = hash_to_point_shake_512({msg}, {salt_a}, {salt_b}).unwrap();")
        lines.append(f"    assert_eq!(got.span(), {const}.span());")
        lines.append("}")
        lines.append("")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--falcon-py", type=Path, default=None,
                        help="optional tprest/falcon.py clone for a cross-check")
    args = parser.parse_args()

    max_salt = 2**160 - 1
    msg, salt_a, salt_b = fixture_vector()
    raw = [
        ("fixture", msg, salt_a, salt_b),
        ("zero", 0, 0, 0),
        ("max", STARK_PRIME - 1, max_salt, max_salt),
    ]
    vectors = [(name, m, a, b, hash_to_point(m, a, b)) for name, m, a, b in raw]
    for name, *_rest, coeffs in vectors:
        assert len(coeffs) == N and all(0 <= c < Q for c in coeffs), name

    if args.falcon_py is not None:
        sys.path.insert(0, str(args.falcon_py))
        import falcon as fpy  # noqa: E402

        scheme = fpy.Falcon(N)
        for name, m, a, b, coeffs in vectors:
            expect = scheme.__hash_to_point__(m.to_bytes(32, "little"), salt_bytes(a, b))
            assert [c % Q for c in expect] == coeffs, f"{name}: falcon.py disagrees"
        print("ok: every vector matches falcon.py's __hash_to_point__")

    OUT.write_text(emit(vectors))
    subprocess.run(["scarb", "fmt", str(OUT)], cwd=REPO, check=True)
    print(f"wrote {OUT.relative_to(REPO)} ({len(vectors)} vectors)")


if __name__ == "__main__":
    main()
