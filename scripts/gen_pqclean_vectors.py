#!/usr/bin/env python3
"""Generate crates/falcon_512/tests/pqclean_interop.cairo: PQClean signatures, verified on-chain.

Builds the signer (signer/, PQClean's Falcon-512 through pqcrypto-falcon), makes a fresh
keypair in a temporary directory, and signs random transaction hashes until there are
COUNT signatures covering both hash-to-point lengths (8 and 9 SHAKE blocks). Every
signature is re-checked here against the on-chain equations with the independent Python
model (hashlib hash-to-point, recursive NTT, schoolbook product). The Cairo test then
requires both verifiers to accept each signature and to reject it over another hash.

The secret key never leaves the temporary directory, which is deleted on exit.

Usage:
    python3 scripts/gen_pqclean_vectors.py [--count 8]
"""

import argparse
import json
import secrets
import subprocess
import tempfile
from pathlib import Path

import gen_falcon_fixture
import gen_ntt_tables
import gen_shake_h2p_kat

REPO = Path(__file__).resolve().parent.parent
SIGNER = REPO / "signer"
BIN = SIGNER / "target" / "release" / "falcon-signer"
OUT = REPO / "crates/falcon_512/tests/pqclean_interop.cairo"
STARK_PRIME = 2**251 + 17 * 2**192 + 1
Q = 12289


def signer(*args) -> dict:
    out = subprocess.run([str(BIN), *args], check=True, capture_output=True, text=True).stdout
    return json.loads(out)


def check(public_key: list[int], message: int, signature: list[int], tables) -> None:
    """The on-chain equations, evaluated with the Python model."""
    h = gen_ntt_tables.intt_rec(gen_falcon_fixture.unpack_512(public_key), tables)
    s1 = gen_falcon_fixture.unpack_512(signature[:29])
    hint = gen_falcon_fixture.unpack_512(signature[31:])
    assert gen_ntt_tables.negacyclic_mul(s1, h) == hint, "hint is not s1 * h"
    point = gen_shake_h2p_kat.hash_to_point(message, signature[29], signature[30])
    centered = gen_falcon_fixture.centered
    norm = sum(centered((point[i] - hint[i]) % Q) ** 2 + centered(s1[i]) ** 2 for i in range(512))
    assert norm <= gen_falcon_fixture.SIG_BOUND_512, "norm above the bound"


def felt_rows(values, indent="        ") -> str:
    return "\n".join(f"{indent}{v}," for v in values)


def emit(public_key: list[str], vectors: list[dict]) -> str:
    parts = [
        "//! GENERATED by `scripts/gen_pqclean_vectors.py` — do not edit by hand.\n"
        "//!\n"
        "//! Interoperability with PQClean's Falcon-512: a keypair and signatures made by PQClean\n"
        "//! (through the `signer/` crate) over random transaction hashes. Both verifiers must\n"
        "//! accept every signature and reject it over a different hash.\n\n"
        "use pqbench_falcon_512::{Falcon512ShakeDirectVerifier, Falcon512ShakeVerifier};\n"
        "use pqbench_interface::PqSignatureVerifier;\n\n"
        "/// The PQClean public key in the account layout (29 felts).\n"
        f"fn public_key() -> Array<felt252> {{\n    array![\n{felt_rows(public_key)}\n    ]\n}}\n",
        "#[test]\n"
        "fn pqclean_public_key_is_valid() {\n"
        "    assert!(Falcon512ShakeVerifier::is_valid_public_key(public_key().span()));\n"
        "    assert!(Falcon512ShakeDirectVerifier::is_valid_public_key(public_key().span()));\n"
        "}\n",
    ]
    for i, v in enumerate(vectors):
        parts.append(
            f"/// Hash-to-point consumes {v['blocks']} SHAKE-256 blocks.\n"
            f"fn message_{i}() -> felt252 {{\n    {v['message']}\n}}\n\n"
            f"fn signature_{i}() -> Array<felt252> {{\n    array![\n{felt_rows(v['signature'])}\n    ]\n}}\n\n"
            "#[test]\n"
            f"fn pqclean_signature_{i}() {{\n"
            f"    let (pk, sig, msg) = (public_key(), signature_{i}(), message_{i}());\n"
            "    let direct = sig.span().slice(0, 31);\n"
            "    assert!(Falcon512ShakeVerifier::verify(msg, pk.span(), sig.span()));\n"
            "    assert!(Falcon512ShakeDirectVerifier::verify(msg, pk.span(), direct));\n"
            "    assert!(!Falcon512ShakeVerifier::verify(msg + 1, pk.span(), sig.span()));\n"
            "    assert!(!Falcon512ShakeDirectVerifier::verify(msg + 1, pk.span(), direct));\n"
            "}\n"
        )
    return "\n".join(parts)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--count", type=int, default=8)
    args = parser.parse_args()
    if args.count < 2:
        parser.error("--count must be at least 2 to cover both hash-to-point lengths")

    subprocess.run(["cargo", "build", "--release", "--quiet", "--manifest-path", str(SIGNER / "Cargo.toml")], check=True)
    roots = next(p for p in gen_ntt_tables.ROOTS_LOCATIONS if p.exists())
    tables = gen_ntt_tables.parse_tables(roots)

    with tempfile.TemporaryDirectory() as tmp:
        key = str(Path(tmp) / "key.json")
        public_key = signer("keygen", "--out", key)["public_key"]
        pk_ints = [int(v, 16) for v in public_key]
        vectors = []
        while len(vectors) < args.count:
            message = secrets.randbelow(STARK_PRIME)
            out = signer("sign", "--key", key, "--hash", hex(message))
            lengths = {v["blocks"] for v in vectors} | {out["blocks"]}
            if len(vectors) == args.count - 1 and len(lengths) < 2:
                continue  # the last slot must add the missing hash-to-point length
            check(pk_ints, message, [int(v, 16) for v in out["signature"]], tables)
            vectors.append({"message": hex(message), "signature": out["signature"], "blocks": out["blocks"]})

    OUT.write_text(emit(public_key, vectors))
    subprocess.run(["scarb", "fmt"], cwd=REPO, check=True)
    blocks = sorted(v["blocks"] for v in vectors)
    print(f"wrote {OUT.relative_to(REPO)}: {len(vectors)} signatures, blocks {blocks}")


if __name__ == "__main__":
    main()
